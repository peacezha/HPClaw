const serviceIndex = new Map(WEB_API_SERVICES.map(service => [service.id, service]));

export function getWebApiService(id: string): WebApiService | undefined {
  return serviceIndex.get(id);
}

export function getWebApiEndpoint(
  service: WebApiService,
  endpointId: string,
): WebApiEndpoint | undefined {
  return service.endpoints.find(endpoint => endpoint.id === endpointId);
}
