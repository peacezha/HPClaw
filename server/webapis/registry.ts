export interface WebApiParam {
  name: string;
  required?: boolean;
  description: string;
  /** 缺省推断：出现在 path 模板里的为 path；GET 其余为 query，POST 其余为 body。 */
  in?: 'path' | 'query' | 'body';
}

export interface WebApiEndpoint {
  id: string;
  name: string;
  method: 'GET' | 'POST';
  /** path 里 {param} 占位，调用时 URL 编码后替换。 */
  path: string;
  description: string;
  params?: WebApiParam[];
}

export interface WebApiProbe {
  /** 指向 endpoints 中某个端点 id。 */
  endpoint: string;
  params?: Record<string, string>;
  expect: { status?: number; contains?: string };
}

export interface WebApiService {
  id: string;
  name: string;
  category: WebApiCategory;
  baseUrl: string;
  description: string;
  homepage: string;
  docsUrl: string;
  authNote?: string;
  endpoints: WebApiEndpoint[];
  probe: WebApiProbe;
}

